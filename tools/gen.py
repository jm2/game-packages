def gen_debian(p: Pkg) -> dict[str, str]:
    parts = int(p.deb.get("parts", 0))
    debarch = [DEB_ARCH[a] for a in p.arch]
    deb_arm = p.aarch64 and not p.native32     # box64 can't run 32-bit x86
    if deb_arm and "arm64" not in debarch and "all" not in debarch:
        debarch.append("arm64")
    arch = " ".join(debarch)
    bdeps = ["debhelper-compat (= 13)"] + p.build_deps("debian") + (["python3"] if p.steam_versioned else [])
    rdeps = p.runtime_deps("debian")
    x86d, emud = p.x86_deps("debian"), p.emu_deps("debian")
    if x86d or (deb_arm and emud):
        rdeps.append("${pt:Depends}")
    if parts:
        rdeps += [f"{p.name}-data{i} (= ${{binary:Version}})" for i in range(1, parts + 1)]
    desc_lines = []
    for para in p.description.split("\n\n"):
        for line in para.splitlines():
            desc_lines.append(" " + line.strip())
        desc_lines.append(" .")
    if desc_lines and desc_lines[-1] == " .":
        desc_lines.pop()
    control = [f"Source: {p.name}", "Section: contrib/games" if p.game else "Section: contrib/games",
               "Priority: optional", f"Maintainer: {MAINTAINER}",
               "Build-Depends: " + ", ".join(bdeps), "Standards-Version: 4.7.0",
               f"Homepage: {p.url}", "Rules-Requires-Root: no", "",
               f"Package: {p.name}", f"Architecture: {arch}",
               "Depends: " + ", ".join(rdeps + ["${misc:Depends}"])]
    if p.deb.get("recommends"):
        control.append("Recommends: " + ", ".join(p.deb["recommends"]))
    prov = [x.split("=")[0] for x in p.provides]
    if prov:
        control.append("Provides: " + ", ".join(prov))
    if p.conflicts:
        control.append("Conflicts: " + ", ".join(p.conflicts))
    if p.replaces:
        control.append("Replaces: " + ", ".join(p.replaces))
        control.append("Breaks: " + ", ".join(p.replaces))
    control.append(f"Description: {p.summary}")
    control += desc_lines
    for i in range(1, parts + 1):
        control += ["", f"Package: {p.name}-data{i}", "Architecture: all", "Depends: ${misc:Depends}",
                    f"Description: {p.summary} (data part {i})",
                    f" Part {i} of the game data for {p.name}, split so no package exceeds",
                    " the .deb size limit. Install the main package instead."]
    D = f"debian/{p.name}"
    rules = ["#!/usr/bin/make -f", f"# {HEADER}", "include /usr/share/dpkg/architecture.mk",
             "export PT_SRCDIR := $(CURDIR)",
             "export PT_WORK := $(CURDIR)/work", "", "%:", "\tdh $@", "",
             "override_dh_auto_build:", "\tdebian/fetch-sources", "\tbash build.sh prepare", "",
             "override_dh_auto_install:", f"\tbash build.sh install {D}"]
    if parts:
        rules.append(f"\tbash build.sh deb-split {D} debian/{p.name}-data {parts}")
    rules += ["", "# Prebuilt game files: leave them exactly as shipped.",
              "override_dh_strip override_dh_dwz override_dh_shlibdeps override_dh_makeshlibs override_dh_strip_nondeterminism:",
              "", "override_dh_builddeb:", "\tdh_builddeb -- -Zzstd -z1", "",
              "# x86 runtime on amd64; FEX/box64 emulation on arm64.",
              "ifeq ($(DEB_HOST_ARCH),arm64)",
              f"PT_DEPENDS := {', '.join(emud)}",
              "else",
              f"PT_DEPENDS := {', '.join(x86d)}",
              "endif",
              "override_dh_gencontrol:",
              ("\tdh_gencontrol -- -v" + DOLLAR + DOLLAR + "(cat work/meta/version)-" + str(p.release)
               + " '-Vpt:Depends=$(PT_DEPENDS)'" if p.steam_versioned
               else "\tdh_gencontrol -- '-Vpt:Depends=$(PT_DEPENDS)'"), "",
              "override_dh_auto_clean:", "\trm -rf work", ""]
    srclines = ["# Upstream files for debian/fetch-sources: <sha256|-> <filename> <url|local>"]
    for s in p.sources():
        if s.get("local"):
            continue
        url = s.get("url", "local")
        if url.startswith(("gogdownloader://", "hib://")):
            url = "local"
        srclines.append(f"{s.get('sha256', '-')} {s['name']} {url}")
    changelog = [f"{p.name} ({p.version}-{p.release}) unstable; urgency=medium", ""]
    changelog += [f"  * {c}" for c in p.changelog]
    changelog += ["", f" -- {MAINTAINER}  {CHANGELOG_DATE.strftime('%a, %d %b %Y %H:%M:%S %z')}", ""]
    copyright_ = ["Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/",
                  f"Upstream-Name: {p.name}", f"Source: {p.url}", "",
                  "Files: *", "Copyright: see the game's own license terms",
                  f"License: {p.license}",
                  *[" " + l for l in p.deb.get("copyright_note",
                    "The game data is not redistributable; this package is built locally from\n"
                    "files you own.").strip().splitlines()], "",
                  "Files: debian/* build.sh package.toml", "Copyright: 2026 John-Michael Mulesa",
                  "License: 0BSD", ""]
    return {
        "debian/control": "\n".join(control) + "\n",
        "debian/rules": "\n".join(rules),
        "debian/changelog": "\n".join(changelog),
        "debian/copyright": "\n".join(copyright_),
        "debian/source/format": "3.0 (native)\n",
        "debian/sources": "\n".join(srclines) + "\n",
        "debian/fetch-sources": (TOOLS / "debian-fetch-sources").read_text(),
    }


