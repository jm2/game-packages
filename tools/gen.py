#!/usr/bin/env python3
"""Generate PKGBUILD, RPM spec and debian/ for packages described by package.toml.

    tools/gen.py [pkgdir ...]      regenerate the given packages (default: all)
    tools/gen.py --check           fail if any generated file is out of date

Each generated package directory contains:
    package.toml       the only file to edit
    build.sh           tools/pkgtool.sh + this package's settings
    <id>.conf          gamelaunch config        (games)
    <id>.desktop       desktop entry            (games)
    README.md          notes shown to users
    PKGBUILD, <name>.spec, debian/*
plus any hand-maintained extra files listed in package.toml (steam_settings/,
patches, local resources).
"""
