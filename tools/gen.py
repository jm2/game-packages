def write(path: Path, content: str, mode: int = 0o644, check: bool = False) -> bool:
    if path.exists() and path.read_text() == content and (path.stat().st_mode & 0o777) == mode:
        return False
    if check:
        print(f"out of date: {path.relative_to(REPO)}")
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(mode)
    return True


