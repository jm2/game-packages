DEB_ARCH = {"x86_64": "amd64", "i686": "i386", "aarch64": "arm64", "any": "all"}


def versioned(name: str, v: str, fmt: str) -> str:
    return {"arch": f"{name}>={v}", "fedora": f"{name} >= {v}", "debian": f"{name} (>= {v})"}[fmt]


def die(msg: str) -> None:
    sys.exit(f"gen.py: {msg}")


def sh(v) -> str:
    return shlex.quote(str(v))


def sh_array(items) -> str:
    return "(" + " ".join(sh(i) for i in items) + ")"


def q1(v) -> str:
    return "'" + str(v).replace("'", "'\\''") + "'"


def bash_single(items) -> str:
    """PKGBUILD-style array with single quotes."""
    return "(" + " ".join("'" + str(i).replace("'", "'\\''") + "'" for i in items) + ")"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


class Pkg:
    def __init__(self, d: Path):
        self.dir = d
        self.t = tomllib.loads((d / "package.toml").read_text())
        t = self.t
        self.name = t["name"]
        if self.name != d.name:
            die(f"{d}: name '{self.name}' must match the directory name")
        self.family = t["family"]
        if self.family not in FAMILIES:
            die(f"{self.name}: unknown family {self.family}")
        self.game, self.wine, self.datasrc = FAMILIES[self.family]
        self.id = t.get("id", "") if self.game else ""
        if self.game and not self.id:
            die(f"{self.name}: games need an id")
        src0 = t.get("source", {})
        self.steam_versioned = bool(src0.get("steam"))
        # Steam packages are versioned at build time (pkgtool: <binary>.b<buildid>).
        self.version = "0" if self.steam_versioned else str(t["version"])
        self.release = int(t.get("release", 1))
        self.summary = t["summary"]
        self.description = t.get("description", self.summary).strip()
        self.url = t["url"]
        self.license = t.get("license", "LicenseRef-Proprietary")
        default_arch = ["any"] if not self.game else ["x86_64"]
        self.arch = t.get("arch", default_arch)
        self.target = t.get("target", f"/opt/{self.id}" if self.game else "")
        self.data_package = t.get("data_package", "")
        # x86 game binaries also run on aarch64 through FEX/box64 (Fedora and
        # Debian; Arch has no aarch64 emulator packages).
        self.aarch64 = bool(t.get("aarch64", self.game))
        self.native32 = bool(t.get("native32", False))
        if not self.target:
            die(f"{self.name}: data packages need an explicit target")
        if self.target == "@prefix" and (self.datasrc != "none" or not self.wine):
            die(f"{self.name}: target = \"@prefix\" is only for wine-launcher packages")
        src = t.get("source", {})
        self.steam = src.get("steam")
        self.files = src.get("files", [])        # [{name, url?, sha256?, extract?, to?}]
        self.gbe = t.get("gbe")
        self.xlln = t.get("xlln", {}).get("enabled", False)
        self.launcher = t.get("launcher", {})
        self.desktop = t.get("desktop", {})
        self.deps = t.get("deps", {})
        self.hooks = t.get("hooks", {})
        self.install = t.get("install", {})
        self.deb = t.get("deb", {})
        self.rpm = t.get("rpm", {})
        self.notes = t.get("notes", "").strip()
        self.extra_files = t.get("extra_files", [])   # hand-kept files shipped as sources
        self.provides = t.get("provides", [])
        self.conflicts = t.get("conflicts", [])
        self.replaces = t.get("replaces", [])
        self.aliases = t.get("aliases", [])
        self.changelog = t.get("changelog", [f"Regenerated from package.toml ({self.version})"])

    # ---- derived ----------------------------------------------------------
    def tools_needed(self) -> list[str]:
        need = ["always"]
        icon = self.t.get("icon", {})
        if icon.get("exe") or icon.get("ico") or icon.get("source_exe"):
            need.append("icon_exe")
        for f in self.files:
            tool = EXTRACT_TOOL.get(f.get("extract", "none"))
            if tool:
                need.append(tool)
        if self.gbe:
            need.append("gbe")
        return need

    def build_deps(self, fmt: str) -> list[str]:
        out: list[str] = []
        for k in self.tools_needed():
            for d in BUILD_TOOLS[k][fmt]:
                if d not in out:
                    out.append(d)
        out += self.deps.get(f"build_{fmt}", [])
        return out

    def gamelaunch_dep(self, fmt: str) -> str:
        # gamelaunch_min: the oldest gamelaunch with the features the config uses.
        v = self.t.get("gamelaunch_min", "1.1.0" if self.target == "@prefix" else "")
        if self.xlln and tuple(map(int, (v or "0").split("."))) < (1, 1, 2):
            v = "1.1.2"                           # 1.1.2: XLLN links into /opt/xlln
        if self.launcher.get("preload") and tuple(map(int, (v or "0").split("."))) < (1, 2, 0):
            v = "1.2.0"                           # 1.2.0: WINE_PRELOAD
        if not v:
            return "gamelaunch"
        return {"arch": f"gamelaunch>={v}", "fedora": f"gamelaunch >= {v}",
                "debian": f"gamelaunch (>= {v})"}[fmt]

    def runtime_deps(self, fmt: str) -> list[str]:
        """Dependencies that are the same on every architecture."""
        out: list[str] = [self.gamelaunch_dep(fmt)] if self.game else []
        if self.gbe:
            # The Windows builds moved to /opt/gbe-fork in 2026.09.27-2.
            win = any(l.lstrip("?").endswith(".dll") for l in self.gbe["libs"])
            out.append(versioned("gbe-fork-bin", "2026.09.27-2", fmt) if win else "gbe-fork-bin")
        if self.xlln:
            out.append(versioned("xlln-bin", "1.6.2.1-2", fmt))
        if self.data_package:
            out.append(self.data_package)
        if self.t.get("icon"):                    # icons go into the hicolor tree
            out.append("hicolor-icon-theme")
        if not (self.game and not self.wine):     # native games' deps are x86 libraries
            out += self.deps.get(fmt, [])
        out += self.deps.get(f"{fmt}_common", [])
        return out

    def x86_deps(self, fmt: str) -> list[str]:
        """Dependencies that only apply where the game runs natively on x86."""
        out: list[str] = []
        if self.wine:
            out += [d for d in WINE_DEPS[fmt] if d != "gamelaunch"]
            # Preload libraries are x86_64 builds; gamelaunch skips missing ones.
            for lib in self.launcher.get("preload", []):
                for prefix, pkg in PRELOAD_PROVIDERS.items():
                    if lib.startswith(prefix) and pkg not in out:
                        out.append(pkg)
        elif self.game:
            # dh_shlibdeps is off for prebuilt game binaries, so declare libc.
            libc = "libc6:i386" if self.native32 else "libc6"
            out += ([libc] if fmt == "debian" else []) + self.deps.get(fmt, [])
        return out

    def emu_deps(self, fmt: str) -> list[str]:
        """Dependencies on aarch64 instead of x86_deps."""
        if not (self.game and self.aarch64):
            return []
        out = ["umu-launcher"] if self.wine else []
        out.append("fex-emu" if fmt == "fedora" or self.native32 else "fex-emu | box64")
        return out

    def sources(self) -> list[dict]:
        """Every file the build reads from PT_SRCDIR, in a fixed order."""
        out = [{"name": "build.sh", "local": True}]
        if self.game:
            out += [{"name": f"{self.id}.conf", "local": True},
                    {"name": f"{self.id}.desktop", "local": True}]
        out.append({"name": "README.md", "local": True})
        for x in self.extra_files:
            out.append({"name": x, "local": True})
        for f in self.files:
            out.append(f)
        return out

    def is_dir_source(self, name: str) -> bool:
        return (self.dir / name).is_dir()


