def version_exe(p: Pkg) -> str:
    """Windows exe whose FileVersion versions the package (relative to the Steam dir)."""
    exe = p.launcher.get("version_exe") or p.launcher.get("exe")
    if not (p.steam and p.wine and exe):
        return ""
    return p.steam.get("subdir", "") + exe


def gen_build_sh(p: Pkg) -> str:
    lines = ["#!/bin/bash", f"# {HEADER}", "",
             f"PT_NAME={sh(p.name)}",
             f"PT_ID={sh(p.id)}",
             f"PT_TARGET={sh(p.target)}",
             f"PT_STEAM_APPID={sh((p.steam or {}).get('appid', ''))}",
             f"PT_REMOVE={sh_array(p.install.get('remove', []))}",
             f"PT_ALIASES={sh_array(p.aliases)}",
             f"PT_EXTRA_PATHS={sh_array(p.install.get('extra_paths', []))}",
             f"PT_ICON_NAME={sh(p.t.get('icon', {}).get('name', ''))}",
             f"PT_NO_DATA={'1' if p.datasrc == 'none' else ''}",
             f"PT_VERSION_EXE={sh(version_exe(p))}",
             f"PT_STEAM_VERSION_BASE={sh(str((p.steam or {}).get('version_base', '')))}",
             f"PT_VERSION_STATIC={sh(p.version)}"]
    if p.gbe:
        libs = p.gbe["libs"]
        lines += [f"PT_GBE_LIBS={sh_array(libs)}",
                  f"PT_GBE_FLAVOUR={sh(p.gbe.get('flavour', 'regular'))}",
                  f"PT_GBE_LINUX_ARCH={sh(p.gbe.get('linux_arch', 'x64'))}"]
    else:
        lines.append("PT_GBE_LIBS=()")
    lines.append("")

    # pt_fetch
    body: list[str] = []
    if p.steam:
        depots = [f"{a}:{d}" for a, d in p.steam.get("depots", [])]
        sub = p.steam.get("subdir", "")
        body.append(f"local dir; dir=$(pt_steam_fetch {sh(p.steam['appid'])} "
                    f"{sh(p.steam.get('platform', 'windows' if p.wine or p.family == 'data-steam' else 'linux'))} "
                    + " ".join(sh(x) for x in depots) + ")")
        body.append('pt_steam_version "$dir" > "$PT_META/version"')
        copy = p.steam.get("copy")
        if copy:
            body.append("local f")
            for pat in copy:
                body.append(f"for f in \"$dir\"/{pat}; do rel=${{f#\"$dir\"/}}; "
                            "install -d \"$PT_GAME/$(dirname \"$rel\")\"; cp -a \"$f\" \"$PT_GAME/$rel\"; done")
        else:
            body.append(f"cp -a \"$dir/{sub}.\" \"$PT_GAME/\"" if sub else "cp -a \"$dir/.\" \"$PT_GAME/\"")
        body.append("rm -rf \"$PT_GAME/steamapps\"")
    for f in p.files:
        kind = f.get("extract", "none")
        if kind == "none":
            continue
        hint = f.get("hint", "")
        dest = f.get("to", "")
        tmp = "$PT_WORK/x-" + re.sub(r"[^A-Za-z0-9._-]", "_", f["name"])
        body.append(f"f=$(pt_need_source {sh(f['name'])} {sh(hint) if hint else ''})")
        if f.get("subdir") is not None or kind in ("inno", "mojo", "zip", "7z", "tar", "iso", "makeself"):
            sub = f.get("subdir", "")
            body.append(f"rm -rf \"{tmp}\"; pt_extract {kind} \"$f\" \"{tmp}\"")
            src = f"{tmp}/{sub}" if sub else tmp
            if f.get("copy"):
                for pat in f["copy"]:
                    body.append(f"for g in \"{src}\"/{pat}; do rel=${{g#\"{src}\"/}}; "
                                f"install -d \"$PT_GAME/{dest}$(dirname \"$rel\")\"; cp -a \"$g\" \"$PT_GAME/{dest}$rel\"; done")
            else:
                body.append(f"install -d \"$PT_GAME/{dest}\"; cp -a \"{src}/.\" \"$PT_GAME/{dest}\"")
        else:  # copy
            body.append(f"install -Dm644 \"$f\" \"$PT_GAME/{dest or f['name']}\"")
    lines.append("pt_fetch() {")
    lines += ["    " + l for l in (body or [":"])]
    lines.append("}")
    lines.append("")

    # pt_icon
    icon = p.t.get("icon", {})
    lines.append("pt_icon() {")
    if icon.get("exe"):
        lines.append(f"    pt_icon_from_exe \"$PT_GAME/{icon['exe']}\"")
    elif icon.get("source_exe"):
        # An exe among the package's sources (e.g. a vendor installer).
        lines.append(f"    pt_icon_from_exe \"$(pt_need_source {sh(icon['source_exe'])})\"")
    elif icon.get("ico"):
        lines.append(f"    local i; for i in \"$PT_GAME\"/{icon['ico']}; do pt_icon_from_ico \"$i\"; break; done")
    elif icon.get("png"):
        lines.append(f"    local i; for i in \"$PT_GAME\"/{icon['png']}; do install -Dm644 \"$i\" \"$PT_META/icon.png\"; break; done")
    elif icon.get("file"):
        lines.append(f"    install -Dm644 \"$PT_SRCDIR/{icon['file']}\" \"$PT_META/icon.png\"")
    else:
        lines.append("    :")
    lines.append("}")
    lines.append("")

    for hook in ("post_prepare", "post_install"):
        if hook in p.hooks:
            lines.append(f"pt_{hook}() {{")
            lines += ["    " + l if l.strip() else "" for l in p.hooks[hook].strip("\n").splitlines()]
            lines.append("}")
            lines.append("")

    lib = (TOOLS / "pkgtool.sh").read_text()
    return "\n".join(lines) + "\n" + lib


