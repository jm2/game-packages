def gen_conf(p: Pkg) -> str:
    l = p.launcher
    out = [f"# gamelaunch config for {p.summary}", f"# {HEADER}",
           f"GAME_NAME={sh(p.desktop.get('name', p.id))}",
           f"GAME_TYPE={'wine' if p.wine else 'native'}",
           f"GAME_DIR={sh(p.target)}",
           f"GAME_EXE={sh(l['exe'])}"]
    if "workdir" in l:
        out.append(f"GAME_WORKDIR={sh(l['workdir'])}")
    if l.get("args"):
        out.append(f"GAME_ARGS={sh_array(l['args'])}")
    if l.get("variants"):
        out.append("VARIANTS=(")
        for v in l["variants"]:
            out.append("    " + sh("|".join([v["flag"], v.get("exe", ""), " ".join(v.get("args", [])), v["description"]])))
        out.append(")")
        if l.get("default_variant"):
            out.append(f"DEFAULT_VARIANT={sh(l['default_variant'])}")
    writable = l.get("writable", p.xlln)
    out.append(f"WRITABLE={1 if writable else 0}")
    if l.get("writable_copy"):
        out.append(f"WRITABLE_COPY={sh_array(l['writable_copy'])}")
    if p.wine:
        out.append(f"DXVK={1 if l.get('dxvk', True) else 0}")
        appid = (p.steam or {}).get("appid")
        umu = l.get("umu_id", f"umu-{appid}" if appid else "")
        if umu:
            out.append(f"UMU_ID={sh(umu)}")
        if l.get("wine_arch"):
            out.append(f"WINE_ARCH={sh(l['wine_arch'])}")
        if l.get("dll_overrides"):
            out.append(f"WINE_DLL_OVERRIDES={sh(l['dll_overrides'])}")
        if l.get("env"):
            out.append(f"WINE_ENV={sh_array(l['env'])}")
        if l.get("prereqs"):
            out.append(f"PREREQS={sh_array(l['prereqs'])}")
        if p.xlln:
            out.append("XLLN=1")
        if l.get("wine_user"):
            out.append(f"WINE_USER={sh(l['wine_user'])}")
        if l.get("preload"):
            out.append(f"WINE_PRELOAD={sh_array(l['preload'])}")
            if l.get("preload_variants"):
                out.append(f"WINE_PRELOAD_VARIANTS={sh_array(l['preload_variants'])}")
        if l.get("bootstrap_url"):
            # A client that installs and updates itself in the prefix (target = "@prefix").
            out.append(f"BOOTSTRAP_URL={sh(l['bootstrap_url'])}")
            if l.get("bootstrap_file"):
                out.append(f"BOOTSTRAP_FILE={sh(l['bootstrap_file'])}")
            if l.get("bootstrap_args"):
                out.append(f"BOOTSTRAP_ARGS={sh_array(l['bootstrap_args'])}")
        legacy = l.get("legacy_dirs", [f"~/.{p.id}/wine"])
        out.append(f"LEGACY_DIRS={sh_array(legacy)}")
    elif l.get("env"):
        out.append(f"NATIVE_ENV={sh_array(l['env'])}")
    if p.native32:
        out.append("NEEDS_X86_32=1")
    return "\n".join(out) + "\n"


def gen_desktop(p: Pkg) -> str:
    d = p.desktop
    name = d.get("name", p.id)
    comment = d.get("comment", p.summary)
    cats = d.get("categories", "Game;")
    if not cats.endswith(";"):
        cats += ";"
    lines = ["[Desktop Entry]", "Type=Application", f"Name={name}", f"Comment={comment}",
             f"Exec={p.id} %U" if d.get("urls") else f"Exec={p.id}", f"Icon={p.id}",
             f"Terminal={'true' if d.get('terminal') else 'false'}", f"Categories={cats}"]
    if d.get("keywords"):
        lines.append(f"Keywords={d['keywords'].rstrip(';')};")
    return "\n".join(lines) + "\n"


def gen_readme(p: Pkg) -> str:
    out = [f"# {p.name}", "", p.description, ""]
    if p.game:
        out += [f"Run it with `{p.id}` or from the desktop menu.", ""]
        if p.wine:
            out += ["This is a Windows game run by `gamelaunch` through umu-launcher (Proton) when",
                    "it is installed, otherwise system wine with your distribution's DXVK. Use",
                    f"`GAMELAUNCH_RUNNER=wine {p.id}` to force system wine. Prefixes and saves",
                    f"live in `~/.local/share/gamelaunch/{p.id}/`; the first start takes a while.", ""]
        if p.launcher.get("variants"):
            out += [f"`{p.id} -h` lists the available modes:", ""]
            for v in p.launcher["variants"]:
                default = " (default)" if v["flag"] == p.launcher.get("default_variant") else ""
                out.append(f"- `-{v['flag']}`: {v['description']}{default}")
            out.append("")
    if p.datasrc == "steam":
        out += ["## Building", "", "Game data comes from Steam via steamcmd, using an account that owns the",
                "game. Either set `STEAM_USER` (steamcmd asks for the password and Steam Guard",
                f"code), or download once with `tools/fetch-steam {p.name}` and build offline from",
                "the cache.", ""]
    elif any(f.get("url", "").startswith(("gogdownloader://", "hib://", "local")) or "url" not in f for f in p.files):
        out += ["## Building", "", "Place these files next to the build files or in",
                f"`${{TMPDIR:-/var/tmp}}/linux-packages-cache/{p.name}/` before building:", ""]
        for f in p.files:
            u = f.get("url", "local")
            if u.startswith(("gogdownloader://", "hib://")) or u == "local":
                where = {"gogdownloader": "GOG (lgogdownloader: " + u.split('://', 1)[-1] + ")",
                         "hib": "Humble Bundle"}.get(u.split(":", 1)[0], f.get("hint", "provided by you"))
                out.append(f"- `{f['name']}` - {where}")
        out.append("")
    skipped = [(fmt, why) for fmt, why in (("Fedora (RPM)", p.rpm.get("disabled")),
                                           ("Debian (.deb)", p.deb.get("disabled"))) if why]
    if skipped:
        out += ["## Formats", "", "Not built for:", ""]
        out += [f"- {fmt}: {why}" for fmt, why in skipped]
        out.append("")
    if p.notes:
        out += ["## Notes", "", p.notes, ""]
    return "\n".join(out)


