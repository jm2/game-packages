# Families with a Windows package: the same files, installed natively.
# native-* need the Windows depots and wine-local/wine-launcher user files or
# a store client, so they get hand-written manifests (or none) instead.
# /opt dirs of our own packages that generated packages may link into.
GOO_LINKED = {"/opt/gbe-fork/": "gbe-fork-bin", "/opt/xlln/": "xlln-bin",
              "/opt/agelanserver-companion/": "agelanserver-companion-bin"}
GOO_FAMILIES = {"wine-steam", "wine-gog", "data-steam", "data-gog", "data-url"}
GOO_ROOT = "<ProgramFiles>/Games"   # admin-only; C:\ lets every user modify new dirs


def toml_str(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def toml_list(items) -> str:
    return "[" + ", ".join(toml_str(i) for i in items) + "]"


def goo_text(s: str) -> str:
    # Linux wording that doesn't apply on Windows.
    return re.sub(r"\s*\(Wine\)|\s+using Wine", "", s)


def goo_name(p: Pkg) -> str:
    # No Wine on Windows: wreckfest-wine-gog -> wreckfest-gog.
    return p.name.replace("-wine-", "-") if p.wine else p.name


def gen_goo(p: Pkg) -> str | None:
    if p.family not in GOO_FAMILIES or p.t.get("goo", {}).get("disabled"):
        return None
    g = p.t.get("goo", {})
    # /opt/X, /usr/share/games/X, /usr/share/X -> C:\Program Files\Games\X (engines too).
    rel = next((p.target.removeprefix(pre) for pre in ("/opt/", "/usr/share/games/", "/usr/share/")
                if p.target.startswith(pre)), None)
    if not rel:
        die(f"{p.name}: no Windows location for target {p.target}")
    base, _, sub = rel.strip("/").partition("/")   # e.g. rvgl, packs/game_files
    stage_dir = f"{base}/{sub}" if sub else base
    deps: dict[str, str] = {}
    if p.data_package:
        deps[p.data_package] = ""
    for d in g.get("deps", []):
        deps[d] = ""
    # [[goo.shortcut]]: extra Start Menu entries, e.g. a data package's
    # shortcut to its engine (with requires = the engine's exe).
    extra_sc = g.get("shortcut", [])
    local = []
    if p.gbe:
        local.append("gbe-fork-bin")
    if p.xlln:
        local.append("xlln-bin")
    # Hooks that link into other packages' /opt dirs (e.g. aoe2-de's companion
    # DLLs) need those packages in the stage, or `cp -aL` can't follow the links.
    hooks = " ".join(p.hooks.values())
    for prefix, pkg in GOO_LINKED.items():
        if prefix in hooks and pkg not in local:
            local.append(pkg)
    # The Linux changelog is about Linux packaging (Wine, gamelaunch, ...).
    notes = g.get("release_notes", [f"Built from linux-packages {p.name} {p.version}-{p.release}"])
    out = [f"# GooGet (Windows) package for {p.name}", f"# {HEADER}",
           f"name = {toml_str(goo_name(p))}",
           f"version = {toml_str(p.version)}",
           f"release = {p.release + g.get('release_offset', 0)}",
           'arch = "noarch"',
           f"description = {toml_str(g.get('description') or goo_text(p.description))}",
           f"license = {toml_str(p.license)}",
           f"url = {toml_str(p.url)}",
           f"release_notes = {toml_list(notes)}",
           f"provides = {toml_list(p.provides)}",
           # googet checks Conflicts before it removes Replaces, so a replaced
           # package listed in both would block the upgrade.
           f"conflicts = {toml_list(goo_conflicts(p))}",
           f"replaces = {toml_list([goo_name_of(c) for c in p.replaces])}",
           "", "[deps]"]
    out += [f"{toml_str(k)} = {toml_str(v)}" for k, v in deps.items()]
    out += ["", "[files]", f"{toml_str(base)} = {toml_str(GOO_ROOT + '/' + base)}"]
    for s in extra_sc:
        out += ["", "[[shortcut]]"]
        out += [f"{k} = {toml_str(v)}" for k, v in s.items()]
    if p.game:
        l = p.launcher
        writable = l.get("writable", p.xlln)
        if writable:
            out += ["", "[writable]", f"dirs = {toml_list([base])}"]
        name = p.desktop.get("name", p.id)
        variants = l.get("variants") or [{"flag": "", "exe": l["exe"], "description": ""}]
        exes = []
        for v in variants:
            exe = v.get("exe") or l["exe"]
            args = " ".join(l.get("args", []) + v.get("args", []))
            label = name if (v["flag"] in ("", l.get("default_variant")) or len(variants) == 1) \
                else f"{name} ({v['description']})"
            workdir = l.get("workdir", "")
            out += ["", "[[shortcut]]", f"name = {toml_str(label)}",
                    f"target = {toml_str(stage_dir + '/' + exe)}",
                    f"args = {toml_str(args)}",
                    f"description = {toml_str(goo_text(p.desktop.get('comment', p.summary)))}"]
            if workdir:
                out.append(f"workdir = {toml_str(stage_dir + '/' + workdir)}")
            if exe not in exes:
                exes.append(exe)
        for exe in exes:
            out += ["", "[[firewall]]", f"name = {toml_str(name + ' (' + exe.split('/')[-1] + ')')}",
                    f"program = {toml_str(stage_dir + '/' + exe)}"]
        for pr in l.get("prereqs", []):
            pname, _, cmd = pr.partition("|")
            if cmd.startswith("winetricks:"):
                continue          # Windows ships or installs these itself
            exe, _, args = cmd.partition(" ")
            out += ["", "[[prereq]]", f"name = {toml_str(pname)}",
                    f"path = {toml_str(stage_dir + '/' + exe)}", f"args = {toml_str(args)}"]
    script = ['export PT_SRCDIR="$PKGDIR" PT_WORK="$WORK"',
              'bash "$PKGDIR/build.sh" prepare',
              'bash "$PKGDIR/build.sh" install "$WORK/root"',
              f'mkdir -p "$STAGE/{stage_dir}"',
              '# Windows needs real files: follow the gbe-fork / xlln links.',
              f'cp -aL "$WORK/root{p.target}/." "$STAGE/{stage_dir}/"',
              f'rm -f "$STAGE/{stage_dir}/.gamelaunch-stamp"']
    if p.xlln:
        xdir = stage_dir + ("/" + p.launcher.get("xlln_dir", "").strip("/") if p.launcher.get("xlln_dir")
                            else ("/" + p.launcher["exe"].rsplit("/", 1)[0] if "/" in p.launcher["exe"] else ""))
        script += [f'mkdir -p "$STAGE/{xdir}/XLiveLessNess"',
                   f'cp -L /opt/xlln/xlive.dll "$STAGE/{xdir}/"',
                   f'cp -aL /opt/xlln/XLiveLessNess/. "$STAGE/{xdir}/XLiveLessNess/"']
    if p.steam_versioned:
        script.append('bash "$PKGDIR/build.sh" version > "$STAGE/.version"')
    # URL sources are fetched by goo-build into PT_CACHE/<linux name>/, where
    # build.sh looks; store downloads (gogdownloader://, steam) must already be
    # cached by tools/fetch-gog / tools/fetch-steam.
    for f in p.files:
        if f.get("url", "").startswith(("http://", "https://")) and f.get("sha256"):
            out += ["", "[[source]]", f"name = {toml_str(f['name'])}",
                    f"url = {toml_str(f['url'])}", f"sha256 = {toml_str(f['sha256'])}"]
    out += ["", "[stage]", 'container = "fedora"', f"source_dir = {toml_str(p.name)}",
            # build.sh reads Steam builds' versions with python3 (as in the spec).
            f"deps = {toml_list(p.build_deps('fedora') + (['python3'] if p.steam_versioned else []))}",
            f"local = {toml_list(local)}",
            "script = '''", *script, "'''"]
    return "\n".join(out) + "\n"


def goo_name_of(name: str) -> str:
    return name.replace("-wine-", "-")


_PROVIDERS: dict[str, list[str]] | None = None


def goo_providers() -> dict[str, list[str]]:
    """Virtual name -> the generated packages that provide it (Linux names)."""
    global _PROVIDERS
    if _PROVIDERS is None:
        _PROVIDERS = {}
        for f in sorted(REPO.glob("*/package.toml")):
            t = tomllib.loads(f.read_text())
            for v in t.get("provides", []):
                _PROVIDERS.setdefault(v.split("=")[0], []).append(t["name"])
    return _PROVIDERS


_GOO_NAMES: set[str] | None = None


def goo_names() -> set[str]:
    """Names googet can see: every Windows package (generated or hand-written)
    and everything they provide."""
    global _GOO_NAMES
    if _GOO_NAMES is None:
        _GOO_NAMES = set()
        for f in sorted(REPO.glob("*/package.toml")):
            t = tomllib.loads(f.read_text())
            if t.get("family") in GOO_FAMILIES \
                    and not t.get("goo", {}).get("disabled"):
                _GOO_NAMES.add(goo_name_of(t["name"]))
                _GOO_NAMES.update(v.split("=")[0] for v in t.get("provides", []))
        for f in sorted(REPO.glob("*/windows/goo.toml")):
            if "Generated by tools/gen.py" in f.read_text():
                continue
            m = tomllib.loads(f.read_text())
            _GOO_NAMES.add(m["name"])
            _GOO_NAMES.update(m.get("provides", []))
    return _GOO_NAMES


def goo_conflicts(p: Pkg) -> list[str]:
    """Windows Conflicts. Linux data packages conflict with the virtual name
    they provide (<app>-data), which pacman, dnf and apt don't apply to the
    package itself. googet (install.go resolveConflicts -> isSatisfied)
    matches a Conflicts entry against every installed package's Provides,
    including the installed older version of the same package, so a virtual
    conflict would block the package's own upgrades. List the other packages
    that provide it by name instead, plus any real names as given."""
    self_name = goo_name(p)
    repl = {goo_name_of(r) for r in p.replaces}
    out: list[str] = []
    for c in p.conflicts:
        if c in p.replaces:
            continue
        names = [n for n in goo_providers().get(c, []) if n != p.name] if c in goo_providers() else [c]
        for n in names:
            n = goo_name_of(n)
            # A wine-* package conflicting with its Linux-native twin (e.g.
            # dirt4-wine-steam vs dirt4-steam) gets that twin's name on Windows.
            # Names only Linux has (an AUR package, a retired package) mean
            # nothing to googet.
            if n not in out and n != self_name and n not in repl and n in goo_names():
                out.append(n)
    return out


def generate(d: Path, check: bool = False) -> bool:
    p = Pkg(d)
    changed = False
    out: dict[str, tuple[str, int]] = {"build.sh": (gen_build_sh(p), 0o755),
                                       "README.md": (gen_readme(p), 0o644)}
    if p.game:
        out[f"{p.id}.conf"] = (gen_conf(p), 0o644)
        out[f"{p.id}.desktop"] = (gen_desktop(p), 0o644)
    # Local checksums must reflect the files as they will be written.
    local_sums: dict[str, str] = {}
    for n, (content, _) in out.items():
        local_sums[n] = hashlib.sha256(content.encode()).hexdigest()
    out["PKGBUILD"] = (gen_pkgbuild(p, local_sums), 0o644)
    # rpm = { disabled = "<why>" }: no Fedora packaging (e.g. libraries Fedora lacks).
    spec = d / f"{p.name}.spec"
    if not p.rpm.get("disabled"):
        out[spec.name] = (gen_spec(p), 0o644)
    elif spec.exists():
        if check:
            print(f"{d.name}: {spec.name} exists but rpm.disabled is set", file=sys.stderr)
        else:
            spec.unlink()
        changed = True
    # deb = { disabled = "<why>" }: no Debian packaging (e.g. a file too big for a .deb).
    if not p.deb.get("disabled"):
        for n, c in gen_debian(p).items():
            out[n] = (c, 0o755 if n in ("debian/rules", "debian/fetch-sources") else 0o644)
    elif (d / "debian").exists():
        if check:
            print(f"{d.name}: debian/ exists but deb.disabled is set", file=sys.stderr)
        else:
            shutil.rmtree(d / "debian")
        changed = True
    goo = gen_goo(p)
    if goo:
        out["windows/goo.toml"] = (goo, 0o644)
    for n, (content, mode) in out.items():
        changed |= write(d / n, content, mode, check)
    if not check:
        # Drop files the generator used to own but no longer does (old launchers).
        for stale in p.t.get("remove_files", []):
            if stale in out:
                continue  # now generated under the same name
            f = d / stale
            if f.exists():
                f.unlink()
                changed = True
    return changed


def main(argv: list[str]) -> int:
    check = "--check" in argv
    dirs = [Path(a).resolve() for a in argv if not a.startswith("--")]
    if not dirs:
        dirs = sorted(x.parent for x in REPO.glob("*/package.toml"))
    bad = False
    for d in dirs:
        if not (d / "package.toml").exists():
            die(f"{d} has no package.toml")
        if generate(d, check):
            bad = True
            if not check:
                print(f"generated {d.name}")
    check_goo_deps()
    return 1 if (check and bad) else 0


def check_goo_deps() -> None:
    """googet (3.4.1) can't resolve a dependency on a name that only exists
    through Provides: listDeps finds the provider but keeps the virtual name
    ("no match found for package quake3-data.noarch..."). Depend on real
    package names until that's fixed upstream."""
    ms = [tomllib.loads(f.read_text()) for f in REPO.glob("*/windows/goo.toml")]
    names = {m["name"] for m in ms}
    for m in ms:
        for dep in m.get("deps", {}):
            if dep not in names:
                die(f"{m['name']}: Windows dependency {dep} is not a package name "
                    "(googet can't install dependencies satisfied only by Provides)")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
