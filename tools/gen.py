def checksum_for(p: Pkg, s: dict) -> str:
    if s.get("local"):
        path = p.dir / s["name"]
        return "SKIP" if path.is_dir() else sha256(path)
    return s.get("sha256", "SKIP")


def gen_pkgbuild(p: Pkg, local_sums: dict[str, str]) -> str:
    src_entries, sums = [], []
    for s in p.sources():
        n = s["name"]
        if s.get("local"):
            src_entries.append(n)
        else:
            url = s.get("url", "local")
            if url == "local":
                src_entries.append(n)  # makepkg finds it next to the PKGBUILD
            else:
                src_entries.append(f"{n}::{url}")
        sums.append(local_sums.get(n) or checksum_for(p, s))
    depends = p.runtime_deps("arch") + p.x86_deps("arch")
    makedepends = p.build_deps("arch")
    if p.datasrc == "steam":
        makedepends += ["steamcmd", "python"]
    optdepends = (WINE_OPTDEPS_ARCH if p.wine else []) + p.deps.get("optional_arch", [])
    arch = p.arch
    L = [f"# {HEADER}", f"# Maintainer: {MAINTAINER_ARCH}", ""]
    L += [f"pkgname={p.name}", f"pkgver={p.version}",
          # makepkg rewrites a line starting with "pkgrel=" to pkgrel=1 when
          # pkgver() changes the version, which would drop every release bump.
          *([f"true && pkgrel={p.release}"] if p.steam_versioned else [f"pkgrel={p.release}"]),
          f"pkgdesc={q1(p.summary)}", f"arch={bash_single(arch)}", f"url={q1(p.url)}",
          f"license={bash_single([p.license])}"]
    for key, val in (("depends", depends), ("makedepends", makedepends), ("optdepends", optdepends),
                     ("provides", p.provides), ("conflicts", p.conflicts), ("replaces", p.replaces)):
        if val:
            L.append(f"{key}={bash_single(val)}")
    L.append("options=('!strip' '!debug' 'emptydirs')")
    L.append("source=(" + "\n        ".join(f'"{e}"' for e in src_entries) + ")")
    noext = [s["name"] for s in p.sources() if not s.get("local")]
    if noext:
        L.append("noextract=(" + "\n           ".join(f'"{n}"' for n in noext) + ")")
    L.append("sha256sums=(" + "\n            ".join(f"'{x}'" for x in sums) + ")")
    if any(s.get("url", "").startswith("gogdownloader://") for s in p.files):
        L += ["", "# GOG installers: download them yourself (lgogdownloader or the website) and put",
              "# them next to this PKGBUILD, or enable lgogdownloader in /etc/makepkg.conf:",
              "#   DLAGENTS+=('gogdownloader::/usr/bin/lgogdownloader --download-file=%u -o %o')",
              "DLAGENTS+=(\"gogdownloader::/usr/bin/echo ==> ERROR: GOG installer %u is missing; see the comment above this line in the PKGBUILD.\")"]
    if any(s.get("url", "").startswith("hib://") for s in p.files):
        L += ["", "# Humble Bundle downloads: put them next to this PKGBUILD.",
              "DLAGENTS+=(\"hib::/usr/bin/echo ==> ERROR: Humble Bundle file %u is missing; download it from your Humble library and place it next to the PKGBUILD.\")"]
    if p.steam_versioned:
        L += ["", "# The version comes from the Steam download: <game version>.b<Steam build ID>.",
              "pkgver() {", '    cat "${srcdir}/work/meta/version"', "}"]
    L += ["", "prepare() {",
          '    PT_SRCDIR="${srcdir}" PT_WORK="${srcdir}/work" bash build.sh prepare',
          "}", "", "package() {",
          '    PT_SRCDIR="${srcdir}" PT_WORK="${srcdir}/work" bash build.sh install "${pkgdir}"',
          "}", ""]
    return "\n".join(L)


